import { createId, isUuid } from "./identifiers.js";
import { TABLES } from "./schema/index.js";
import { COLUMN_TARGETS, POLYMORPHIC, RETIRED_TABLES } from "./relationships.js";

// mysql2 only reports AUTO_INCREMENT values in insertId. This adapter supplies an
// application UUID before the INSERT and preserves the existing insertId contract.
// It wraps pooled and transaction connections equally; no extra query or table.
const wrapped = new WeakMap();

function valueGroups(sql, offset) {
  const groups = [];
  let depth = 0;
  let quote = null;
  let start;
  for (let i = offset; i < sql.length; i++) {
    const ch = sql[i];
    if (quote) {
      if (ch === "\\") { i++; continue; }
      if (ch === quote) {
        if (sql[i + 1] === quote) { i++; continue; }
        quote = null;
      }
      continue;
    }
    if (ch === "'" || ch === '"' || ch === "`") { quote = ch; continue; }
    if (depth === 0 && /\s|,/.test(ch)) continue;
    if (depth === 0 && ch !== "(") break; // ON DUPLICATE KEY UPDATE
    if (ch === "(") { if (depth === 0) start = i; depth++; }
    if (ch === ")" && --depth === 0) groups.push([start, i + 1]);
  }
  if (depth || quote) throw new Error("Unbalanced INSERT values.");
  return groups;
}

function placeholderCount(sql) {
  let count = 0;
  let quote = null;
  for (let i = 0; i < sql.length; i++) {
    const ch = sql[i];
    if (quote) {
      if (ch === "\\") { i++; continue; }
      if (ch === quote) {
        if (sql[i + 1] === quote) { i++; continue; }
        quote = null;
      }
    } else if (ch === "'" || ch === '"' || ch === "`") quote = ch;
    else if (ch === "?") count++;
  }
  return count;
}

export function prepareUuidInsert(sql, values = [], newId = createId) {
  if (typeof sql !== "string") throw new TypeError("Use a SQL string with positional parameters.");
  if (!/^\s*(INSERT|REPLACE)\b/i.test(sql)) return { sql, values, ids: [] };
  const match = sql.match(/^\s*(?:INSERT(?:\s+IGNORE)?|REPLACE)\s+INTO\s+`?(\w+)`?\s*\(([^)]+)\)\s*VALUES\s*/i);
  if (!match || !Object.hasOwn(TABLES, match[1])) throw new Error("INSERT must name a modeled table, columns, and VALUES.");
  const columns = match[2].split(",").map(column => column.trim().replaceAll("`", ""));
  if (columns.includes("id")) throw new Error("IDs are generated by the model persistence adapter; omit id from INSERT columns.");
  const prefix = match[0].replace(/\(([^)]+)\)/, "(id, $1)");
  const offset = match[0].length;
  const ids = [];
  if (sql[offset] === "?") {
    if (!Array.isArray(values[0]) || values[0].some(row => !Array.isArray(row) || row.length !== columns.length)) {
      throw new Error("Bulk INSERT must provide a row array matching its columns.");
    }
    const rows = values[0].map(row => { const id = newId(); ids.push(id); return [id, ...row]; });
    return { sql: prefix + sql.slice(offset), values: [rows, ...values.slice(1)], ids };
  }
  const groups = valueGroups(sql, offset);
  if (!groups.length) throw new Error("INSERT requires at least one VALUES tuple.");
  let rewritten = prefix;
  let cursor = offset;
  let parameter = 0;
  const parameters = [];
  for (const [start, end] of groups) {
    const id = newId();
    ids.push(id);
    rewritten += sql.slice(cursor, start) + "(?, " + sql.slice(start + 1, end);
    const count = placeholderCount(sql.slice(start, end));
    parameters.push(id, ...values.slice(parameter, parameter + count));
    parameter += count;
    cursor = end;
  }
  rewritten += sql.slice(cursor);
  parameters.push(...values.slice(parameter));
  return { sql: rewritten, values: parameters, ids };
}

export function withUuidPersistence(connection) {
  if (wrapped.has(connection)) return wrapped.get(connection);
  const proxy = new Proxy(connection, {
    get(target, property) {
      if (property === "getConnection") return async () => withUuidPersistence(await target.getConnection());
      if (property === "execute" || property === "query") return async (sql, values = []) => {
        const prepared = prepareUuidInsert(sql, values);
        const result = await target[property](prepared.sql, prepared.values);
        if (prepared.ids.length && result[0]?.affectedRows === 1 && !/\bON\s+DUPLICATE\s+KEY\b/i.test(sql)) {
          result[0] = { ...result[0], insertId: prepared.ids[0] };
        }
        return result;
      };
      const value = Reflect.get(target, property, target);
      return typeof value === "function" ? value.bind(target) : value;
    },
  });
  wrapped.set(connection, proxy);
  wrapped.set(proxy, proxy);
  return proxy;
}

export async function assertUuidSchema(connection) {
  const [columns] = await connection.query(
    `SELECT table_name AS table_name, column_name AS column_name, data_type AS data_type,
            character_maximum_length AS character_maximum_length
     FROM information_schema.columns WHERE table_schema = DATABASE()`
  );
  const isIdentity = column => column.column_name === "id" || Object.hasOwn(COLUMN_TARGETS, column.column_name) ||
    Object.hasOwn(POLYMORPHIC[column.table_name] || {}, column.column_name) && !["reference_id", "target_id"].includes(column.column_name) ||
    column.table_name === "admin_audit_logs" && column.column_name === "targetId";
  const legacy = columns.filter(column => Object.hasOwn(TABLES, column.table_name) && isIdentity(column) &&
    (String(column.data_type).toLowerCase() !== "char" || Number(column.character_maximum_length) !== 36));
  if (legacy.length) throw new Error(`UUID migration required for: ${legacy.map(column => `${column.table_name}.${column.column_name}`).join(", ")}. Enable deployment transfer using models/README.md, or inspect with npm run db:migrate:uuid -- --plan.`);
  if (columns.some(column => RETIRED_TABLES.includes(column.table_name))) throw new Error("Incomplete relational migration: deployment transfer must consolidate legacy tables before starting the backend.");
  // Do not turn a partially completed conversion into a running application.
  for (const column of columns.filter(column => Object.hasOwn(TABLES, column.table_name) && column.column_name === "id")) {
    const [invalid] = await connection.query(`SELECT id FROM \`${column.table_name}\` WHERE id IS NOT NULL AND id NOT REGEXP ? LIMIT 1`, ["^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[1-8][0-9a-fA-F]{3}-[89abAB][0-9a-fA-F]{3}-[0-9a-fA-F]{12}$"]);
    if (invalid.length && !isUuid(invalid[0].id)) throw new Error(`Incomplete UUID migration in ${column.table_name}; finish migration before starting the backend.`);
  }
}
